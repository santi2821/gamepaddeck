/**
 * Normalize brand string to canonical brand
 */
export function normalizeBrand(brand: ControllerBrand | string): 'xbox' | 'sony' | 'nintendo' {
  const b = brand.toLowerCase();
  if (b.includes('sony') || b.includes('playstation') || b.includes('ps5') || b.includes('ps4')) {
    return 'sony';
  }
  if (b.includes('switch') || b.includes('nintendo')) {
    return 'nintendo';
  }
  return 'xbox';
}

/**
 * Get full body SVG URL for a controller brand
 */
export function getControllerBodySvg(
  brand: ControllerBrand | string,
  theme: 'dark' | 'light' = 'dark'
): string {
  const canonical = normalizeBrand(brand);
  switch (canonical) {
    case 'sony':
      return theme === 'light' ? PLAYSTATION_ASSETS.controllerAlt || PLAYSTATION_ASSETS.controller : PLAYSTATION_ASSETS.controller;
    case 'nintendo':
      return SWITCH_ASSETS.controller;
    case 'xbox':
    default:
      return theme === 'light' ? XBOX_ASSETS.controllerAlt || XBOX_ASSETS.controller : XBOX_ASSETS.controller;
  }
}

/**
 * Standard HTML5 Gamepad button mapping to button name keys:
 * 0: South (A / Cross / B)
 * 1: East (B / Circle / A)
 * 2: West (X / Square / Y)
 * 3: North (Y / Triangle / X)
 * 4: L1 / LB
 * 5: R1 / RB
 * 6: L2 / LT
 * 7: R2 / RT
 * 8: Select / Share / Back / Minus / Create
 * 9: Start / Options / Menu / Plus
 * 10: L3 / LS Click
 * 11: R3 / RS Click
 * 12: Dpad Up
 * 13: Dpad Down
 * 14: Dpad Left
 * 15: Dpad Right
 * 16: Guide (Xbox / PS / Home)
 * 17: Touchpad / Capture / Share
 */
const STANDARD_BUTTON_MAP: Record<'xbox' | 'sony' | 'nintendo', string[]> = {
  xbox: [
    'a', 'b', 'x', 'y',
    'lb', 'rb', 'lt', 'rt',
    'view', 'menu', 'ls-click', 'rs-click',
    'dpad-up', 'dpad-down', 'dpad-left', 'dpad-right',
    'xbox', 'share'
  ],
  sony: [
    'cross', 'circle', 'square', 'triangle',
    'l1', 'r1', 'l2', 'r2',
    'create', 'options', 'l3', 'r3',
    'dpad-up', 'dpad-down', 'dpad-left', 'dpad-right',
    'ps', 'touchpad'
  ],
  nintendo: [
    'b', 'a', 'y', 'x',
    'l', 'r', 'zl', 'zr',
    'minus', 'plus', 'ls-click', 'rs-click',
    'dpad-up', 'dpad-down', 'dpad-left', 'dpad-right',
    'home', 'capture'
  ],
};

/**
 * Get prompt SVG URL for a specific button name or HTML5 button index
 */
export function getButtonPrompt(
  brand: ControllerBrand | string,
  button: string | number
): string | undefined {
  const canonical = normalizeBrand(brand);
  const pack = canonical === 'sony' ? PLAYSTATION_ASSETS : canonical === 'nintendo' ? SWITCH_ASSETS : XBOX_ASSETS;

  if (typeof button === 'number') {
    const map = STANDARD_BUTTON_MAP[canonical];
    const key = map[button];
    if (key && pack.buttons[key]) {
      return pack.buttons[key];
    }
  }

  const key = String(button).toLowerCase().trim();
  return pack.buttons[key] || XBOX_ASSETS.buttons[key];
}

/**
 * React Component to render an authentic Controller body image
 */
export const ControllerImage: React.FC<{
  brand: ControllerBrand | string;
  theme?: 'dark' | 'light';
  className?: string;
  style?: React.CSSProperties;
  alt?: string;
}> = ({ brand, theme = 'dark', className, style, alt }) => {
  const src = getControllerBodySvg(brand, theme);
  const brandName = normalizeBrand(brand);
  return React.createElement('img', {
    src,
    alt: alt || `${brandName} controller`,
    className,
    style: {
      maxWidth: '100%',
      height: 'auto',
      display: 'block',
      ...style,
    },
    loading: 'lazy',
  });
};

/**
 * React Component to render an authentic Button Prompt SVG badge
 */
export const ButtonPrompt: React.FC<{
  brand: ControllerBrand | string;
  button: string | number;
  size?: number;
  className?: string;
  style?: React.CSSProperties;
  alt?: string;
}> = ({ brand, button, size = 28, className, style, alt }) => {
  const src = getButtonPrompt(brand, button);
  if (!src) return null;

  return React.createElement('img', {
    src,
    alt: alt || `Button ${button}`,
    className,
    style: {
      width: `${size}px`,
      height: `${size}px`,
      objectFit: 'contain',
      display: 'inline-block',
      verticalAlign: 'middle',
      ...style,
    },
    loading: 'lazy',
  });
};
